#!/usr/bin/env python3
"""Build the public prompt command reference from an explicit first-party allowlist.

Reads source as text/AST only: never imports a lab, runs a command, reads a real
.env, or discovers user/private files. --check detects stale committed output.
"""
import argparse
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs/HOW_TO_USE_COMMANDS.md"
MAKEFILES = ["win-lab/Makefile", "linux-lab/Makefile", "ios-lab/Makefile",
             "android-lab/lab/Makefile", "source-lab/Makefile", "firewall-lab/vm/Makefile"]
PARSERS = [
    "console/content.py",
    "android-lab/lab/orchestrator.py",
    *[f"android-lab/lab/scripts/{name}.py" for name in (
        "app_reporter", "secret_scanner", "apk_patcher", "agentic_engine",
        "sandbox_dumper", "ipc_fuzzer", "device_monitor", "logcat_monitor", "mobsf_client")],
    "source-lab/engine/source_lab/cli/run_detection.py",
    "source-lab/engine/source_lab/contracts.py",
    "source-lab/engine/source_lab/sourcemap/__main__.py",
    *[f"source-lab/engine/source_lab/pipeline/{name}.py" for name in (
        "ext_repo_analyzer", "ext_merger", "merge_csvs")],
    "source-lab/engine/source_lab/import_legacy.py",
    "firewall-lab/vm/scripts/render-rules.py",
    "firewall-lab/scripts/catalog.py",
]
EXAMPLES = ["win-lab/.env.example", "linux-lab/.env.example", "ios-lab/.env.example",
            "ios-lab/mac/config.env.example", "android-lab/lab/.env.example",
            "source-lab/.env.example", "firewall-lab/vm/.env.example"]


def read(path):
    return (ROOT / path).read_text(encoding="utf-8-sig")


def build():
    out = ["# Generated technical command inventory", "",
           "Generated by `python3 scripts/build-how-to-use-reference.py` from the",
           "explicit source files below. This is shipped source context, not host",
           "discovery. No commands are executed. Configuration **names only** are",
           "included; configuration values/credentials are not included, and no private",
           "inputs are read.", "",
           "## Shared CLI grammar (`labctl`)", "", "```text",
           read("labctl").split("cat <<'EOF'", 1)[1].split("\nEOF", 1)[0].strip(), "```", "",
           "The CLI help is reproduced as shipped. Platform readiness and the",
           "operational cheatsheet qualify its applicability (for example disk",
           "resize is also implemented for Linux/iOS VM paths; inspect their runbooks).", ""]
    for path in MAKEFILES:
        out += [f"## Make targets: `{path}`", "",
                f"Run from the checkout root as `make -C {Path(path).parent} TARGET [VARIABLE=value ...]`.", ""]
        for line in read(path).splitlines():
            match = re.match(r"^([\w -]+):(?!=)(.*)", line)
            if match:
                names, rest = match.groups()
                if names.startswith("."):
                    continue
                description = rest.split("##", 1)[1].strip() if "##" in rest else "See target recipe in this Makefile."
                out.append(f"- `{names.strip()}` — {description}")
        out.append("")
    out += ["## Python CLI parser declarations", "",
            "These are exact argparse declarations, in source order, including",
            "subcommands, positional arguments, choices, defaults and required flags.",
            "They describe CLI syntax; the Python declarations are **not shell commands**.",
            "Use the invocation prefixes in the operational cheatsheet. Parser defaults",
            "can be overridden by wrappers such as source-lab/run.py; use those wrappers.", ""]
    for path in PARSERS:
        source = read(path)
        tree = ast.parse(source)
        calls = sorted((node for node in ast.walk(tree)
                        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                        and node.func.attr in {"add_argument", "add_parser"}), key=lambda node: node.lineno)
        if calls:
            out += [f"### `{path}`", "", "```python"]
            out += [" ".join(ast.get_source_segment(source, node).split()) for node in calls]
            out += ["```", ""]
    source = read("android-lab/lab/lab.ps1")
    params = source.split("[CmdletBinding()]", 1)[1].split("\n)", 1)[0]
    out += ["## Windows Android PowerShell syntax", "",
            "From android-lab/lab: `.\\lab.ps1 COMMAND [parameters]`.", "",
            "Accepted commands (from the actual ValidateSet):", "",
            re.search(r"\[ValidateSet\((.*?)\)\]", params, re.S)[1], "",
            "Parameters (names/types only; values are supplied by the operator):", ""]
    out += [f"- `{kind} ${name}`" for kind, name in re.findall(r"\[(string|int|switch)\]\$(\w+)", params)]
    out.append("")
    for path in EXAMPLES:
        keys = list(dict.fromkeys(re.findall(r"^\s*(?:#\s*)?([A-Z][A-Z0-9_]*)=", read(path), re.M)))
        out += [f"## Configuration keys: `{path}`", "", ", ".join(f"`{key}`" for key in keys), ""]
    out += ["## Android Python dependency pins", "",
            "Source: android-lab/lab/requirements.txt. These are shipped pins, not",
            "proof that every package installs on every Python/host. Use the host's",
            "documented installer/venv path and report compatibility failures; Source",
            "static and the minimal console do not need this heavy dependency set.", "",
            "```text", read("android-lab/lab/requirements.txt").strip(), "```", ""]
    for path in ["dashboard/package.json", "app/package.json"]:
        package = json.loads(read(path))
        out += [f"## npm scripts: `{path}`", "",
                "Developer/maintainer commands; use only when relevant to the task.", ""]
        out += [f"- `npm run {name}` — `{command}`" for name, command in package["scripts"].items()]
        out.append("")
    out += ["## Reference sources", "",
            "Every path above is relative to https://github.com/keyvanarasteh/os-lab .",
            "For a direct source link use https://github.com/keyvanarasteh/os-lab/blob/master/PATH .", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, "Prompt reference is stale: run python3 scripts/build-how-to-use-reference.py\n")
        print("Prompt command reference matches all allowlisted sources.")
    else:
        OUTPUT.write_text(expected)
        print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(expected):,} characters).")


if __name__ == "__main__":
    main()
