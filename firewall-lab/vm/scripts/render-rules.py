#!/usr/bin/env python3
"""Render a company's rule set onto a chosen firewall backend.

The rules in a company.json are written once, abstractly (action / direction /
proto / port / from / to / note). The whole point of class was that this policy —
and especially the **ordering and default rules** — is the same idea on every
firewall; UFW was just where we started. So this renders to several targets:

    --target ufw     Ubuntu UFW commands (the teaching baseline)
    --target nft      nftables ruleset (what pfSense/OPNsense run underneath)
    --target table    vendor-neutral policy table you translate onto any GUI/CLI
                       (FortiGate, pfSense, OPNsense, Sophos, ...)

Usage:
    python3 render-rules.py <slug> [--branch <id>] [--segment <name>] \
        [--target ufw|nft|table] [--ssh-port 22] [--reset] [-o out]

Stdlib only. Shell/nft output is meant to run INSIDE a disposable guest (see
../README.md), never on your host. Symbolic endpoints (e.g. "dmz-web") that are
not CIDRs and not a known VLAN are kept as `any` with a note — scope them on
real kit.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # firewall-lab/
COMPANIES = ROOT / "companies"
CIDR_RE = re.compile(r"^\d{1,3}(\.\d{1,3}){3}/\d{1,2}$")
IP_RE = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")


def one_line(text) -> str:
    """Collapse whitespace (including newlines) so text is safe inside a # comment."""
    return " ".join(str(text).split())


def shell_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def resolve(ref, vlan_cidr):
    """Return (address, annotation). Named segments map to a VLAN CIDR when known."""
    if not ref or str(ref).lower() == "any":
        return "any", None
    ref = str(ref)
    if CIDR_RE.match(ref) or IP_RE.match(ref):
        return ref, None
    key = ref.lower()
    if key in vlan_cidr:
        return vlan_cidr[key], f"{ref}={vlan_cidr[key]}"
    return "any", f"{ref} (symbolic)"


PORT_RE = re.compile(r"^(\d{1,5})(?::(\d{1,5}))?$")
PORT_PROTOS = ("tcp", "udp", "any")


def port_parts(port):
    """Split a rule port ("22", "22,443", "1514:1515", "6881:6889,6969") into parts.

    Returns None when any part is not a port or port range (e.g. "esp"), so the
    caller can skip the rule instead of emitting an invalid or broadened one.
    """
    parts = [p.strip() for p in str(port).split(",")]
    for part in parts:
        m = PORT_RE.match(part)  # an empty item ("80,,443") does not match
        if not m:
            return None
        lo, hi = int(m.group(1)), int(m.group(2) or m.group(1))
        if not (1 <= lo <= hi <= 65535):
            return None
    return parts


def l4_protos(proto):
    """Protocols a port match applies to: proto "any" + port means TCP and UDP.

    Only called for PORT_PROTOS; a port on icmp (or another protocol) is ignored by
    both renderers so UFW and nft apply the same policy.
    """
    return [proto] if proto in ("tcp", "udp") else ["tcp", "udp"]


def skipped(port, note):
    """Comment line for a rule that cannot be rendered; also warns on stderr."""
    print(f"warning: rule skipped, unsupported port {port!r}: {note}", file=sys.stderr)
    return f"# SKIPPED (unsupported port {port!r}, translate by hand): {note}"


def rule_note(rule, src_note, dst_note):
    """One-line note. Line breaks are flattened: the note goes into shell and nft
    comments, and a newline there would end the comment and run the rest."""
    bits = [one_line(rule["note"])]
    if src_note:
        bits.append(f"from {src_note}")
    if dst_note:
        bits.append(f"to {dst_note}")
    return " · ".join(bits)


# ── UFW ────────────────────────────────────────────────────────────────────
def render_ufw(company, branch, firewalls, vlan_cidr, ssh_port, reset):
    out = [
        "#!/usr/bin/env bash",
        "# AUTO-GENERATED by render-rules.py --target ufw — review before running.",
        f"# {one_line(company['name'])} / {one_line(branch['name'])}",
        "set -euo pipefail",
        'if [ "$(id -u)" -ne 0 ]; then echo "run as root"; exit 1; fi',
        "",
    ]
    if reset:
        out += ["ufw --force reset", ""]
    out += [
        "# SSH first — never lock yourself out before enabling the firewall.",
        f"ufw allow {ssh_port}/tcp comment 'admin SSH'",
        "# Default rules: the backbone of the policy (deny in, allow out).",
        "ufw default deny incoming",
        "ufw default allow outgoing",
        "ufw logging on",
        "",
    ]
    for fw in firewalls:
        out.append(f"# ── {one_line(fw['segment'])} · {one_line(fw['chosen']['product'])} ({one_line(fw['chosen']['vendor'])}) — first match wins")
        for r in fw["rules"]:
            src, sn = resolve(r.get("from"), vlan_cidr)
            dst, dn = resolve(r.get("to"), vlan_cidr)
            proto = r.get("proto", "any")
            direction = r.get("direction", "in")
            note = shell_quote(rule_note(r, sn, dn)[:255])
            port = r.get("port")
            if port is not None and proto in PORT_PROTOS:
                ports = port_parts(port)
                if ports is None:
                    out.append(skipped(port, rule_note(r, sn, dn)))
                    continue
                # UFW needs an explicit tcp/udp for a port match; "any" becomes one rule per protocol.
                variants = [(p, ",".join(ports)) for p in l4_protos(proto)]
            else:
                variants = [(proto if proto != "any" else None, None)]
            for vproto, vport in variants:
                parts = ["ufw"]
                if direction == "forward":
                    parts.append("route")
                parts.append(r["action"])
                if direction in ("in", "out"):
                    parts.append(direction)
                if vproto:
                    parts += ["proto", vproto]
                parts += ["from", src, "to", dst]
                if vport:
                    parts += ["port", vport]
                parts += ["comment", note]
                out.append(" ".join(parts))
        out.append("")
    out += ["ufw --force enable", "ufw status numbered", ""]
    return "\n".join(out)


# ── nftables ─────────────────────────────────────────────────────────────────
NFT_ACTION = {"allow": "accept", "deny": "drop", "reject": "reject", "limit": "accept"}
NFT_CHAIN = {"in": "input", "out": "output", "forward": "forward"}


def _nft_match(r, vlan_cidr):
    src, sn = resolve(r.get("from"), vlan_cidr)
    dst, dn = resolve(r.get("to"), vlan_cidr)
    frags = []
    if src != "any":
        frags.append(f"ip saddr {src}")
    if dst != "any":
        frags.append(f"ip daddr {dst}")
    proto = r.get("proto", "any")
    port = r.get("port")
    if port is not None and proto in PORT_PROTOS:
        ports = port_parts(port)
        if ports is None:
            return skipped(port, rule_note(r, sn, dn))
        ports = [p.replace(":", "-") for p in ports]
        # A comma list must be an anonymous set: "dport { 22, 443 }", not "dport 22,443".
        dport = ports[0] if len(ports) == 1 else "{ " + ", ".join(ports) + " }"
        if proto == "any":
            # Never drop the port: "any" + port means TCP or UDP to those ports, not all traffic.
            frags.append(f"meta l4proto {{ tcp, udp }} th dport {dport}")
        else:
            frags.append(f"{proto} dport {dport}")
    elif proto in ("tcp", "udp"):
        frags.append(f"meta l4proto {proto}")
    elif proto == "icmp":
        frags.append("meta l4proto icmp")
    verdict = NFT_ACTION[r["action"]]
    if r["action"] == "limit":
        frags.append("limit rate 6/minute")
    frags.append(verdict)
    # nft comments are double-quoted strings: keep inner quotes from ending them early.
    comment = rule_note(r, sn, dn).replace('"', "'")[:63]
    frags.append(f'comment "{comment}"')
    return " ".join(frags)


def render_nft(company, branch, firewalls, vlan_cidr, ssh_port, reset):
    by_chain = {"input": [], "output": [], "forward": []}
    for fw in firewalls:
        for r in fw["rules"]:
            by_chain[NFT_CHAIN.get(r.get("direction", "in"), "input")].append((fw["segment"], r))
    out = [
        "#!/usr/sbin/nft -f",
        "# AUTO-GENERATED by render-rules.py --target nft — the packet-filter view.",
        f"# {one_line(company['name'])} / {one_line(branch['name'])}. Default policy drop on input/forward.",
        "flush ruleset",
        "",
        "table inet filter {",
    ]
    chain_policy = {"input": "drop", "forward": "drop", "output": "accept"}
    for chain in ("input", "forward", "output"):
        hook = chain
        out.append(f"  chain {chain} {{")
        out.append(f"    type filter hook {hook} priority 0; policy {chain_policy[chain]};")
        out.append("    ct state established,related accept")
        if chain == "input":
            out.append("    iif lo accept")
            out.append(f"    tcp dport {ssh_port} accept comment \"admin SSH\"")
        last_seg = None
        for seg, r in by_chain[chain]:
            if seg != last_seg:
                out.append(f"    # {one_line(seg)}")
                last_seg = seg
            out.append(f"    {_nft_match(r, vlan_cidr)}")
        out.append("  }")
    out.append("}")
    out.append("")
    return "\n".join(out)


# ── vendor-neutral table ─────────────────────────────────────────────────────
def render_table(company, branch, firewalls, vlan_cidr, ssh_port, reset):
    out = [
        f"# Policy table — {one_line(company['name'])} / {one_line(branch['name'])}",
        "# Vendor-neutral. Translate top-to-bottom (first match wins) onto any product:",
        "# FortiGate policy list, pfSense/OPNsense rules, Sophos, etc.",
        "# Default rules: INPUT deny, OUTPUT allow, FORWARD deny.",
        f"# Admin: allow tcp/{ssh_port} over VPN only (not from the internet).",
        "",
    ]
    header = ("#", "ACTION", "DIR", "PROTO", "PORT", "FROM", "TO", "NOTE")
    rows = [header]
    n = 0
    for fw in firewalls:
        for r in fw["rules"]:
            n += 1
            src, _ = resolve(r.get("from"), vlan_cidr)
            dst, _ = resolve(r.get("to"), vlan_cidr)
            rows.append(
                (
                    str(n),
                    r["action"],
                    r.get("direction", "in"),
                    r.get("proto", "any"),
                    str(r.get("port", "-")),
                    r.get("from", "any"),
                    r.get("to", "any"),
                    r["note"],
                )
            )
    widths = [max(len(row[i]) for row in rows) for i in range(len(header) - 1)]
    for i, row in enumerate(rows):
        fixed = "  ".join(row[j].ljust(widths[j]) for j in range(len(widths)))
        out.append(f"{fixed}  {row[-1]}")
        if i == 0:
            out.append("  ".join("-" * widths[j] for j in range(len(widths))) + "  " + "-" * 4)
    out.append("")
    return "\n".join(out)


RENDERERS = {"ufw": render_ufw, "nft": render_nft, "table": render_table}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("slug")
    ap.add_argument("--branch")
    ap.add_argument("--segment")
    ap.add_argument("--target", choices=list(RENDERERS), default="ufw")
    ap.add_argument("--ssh-port", type=int, default=22)
    ap.add_argument("--reset", action="store_true")
    ap.add_argument("-o", "--out")
    args = ap.parse_args(argv)

    manifest = COMPANIES / args.slug / "company.json"
    if not manifest.exists():
        ap.error(f"no such company: {manifest}")
    company = json.loads(manifest.read_text(encoding="utf-8"))

    branches = company["branches"]
    branch = next((b for b in branches if b["id"] == args.branch), None) if args.branch else branches[0]
    if branch is None:
        ap.error(f"no branch {args.branch!r}; have: {', '.join(b['id'] for b in branches)}")

    vlan_cidr = {v["name"].lower(): v["cidr"] for v in branch["network"].get("vlans", [])}
    firewalls = [f for f in branch["firewalls"] if args.segment is None or f["segment"] == args.segment]
    if not firewalls:
        ap.error(f"no firewall for segment {args.segment!r} in branch {branch['id']}")

    text = RENDERERS[args.target](company, branch, firewalls, vlan_cidr, args.ssh_port, args.reset)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
