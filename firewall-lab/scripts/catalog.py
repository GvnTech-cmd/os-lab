#!/usr/bin/env python3
"""Collect every firewall across all companies into one structured catalog.

As students open PRs adding companies, this builds the running list of firewalls
and their detailed properties — vendor, product, throughput, price, segment,
rule counts and action breakdown, and the alternatives that were compared. CI
runs it on every PR so the catalog always reflects what's been submitted.

Writes:
  firewall-lab/catalog.json   structured — one row per firewall + aggregates
  firewall-lab/catalog.md     a readable table + vendor/product tallies

    python3 firewall-lab/scripts/catalog.py            # regenerate both
    python3 firewall-lab/scripts/catalog.py --check     # fail if out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPANIES = ROOT / "companies"
JSON_OUT = ROOT / "catalog.json"
MD_OUT = ROOT / "catalog.md"
ACTIONS = ("allow", "deny", "reject", "limit")


def collect() -> dict:
    rows: list[dict] = []
    contributors: list[dict] = []
    for folder in sorted(p for p in COMPANIES.iterdir() if p.is_dir()):
        manifest = folder / "company.json"
        if not manifest.exists():
            continue
        c = json.loads(manifest.read_text(encoding="utf-8"))
        if c.get("author", {}).get("github") and c.get("author", {}).get("name") != "Seed Example":
            contributors.append({"slug": c["slug"], "company": c["name"], "github": c["author"]["github"]})
        for b in c["branches"]:
            for fw in b["firewalls"]:
                action_counts = Counter(r["action"] for r in fw["rules"])
                chosen = fw["chosen"]
                rows.append(
                    {
                        "company": c["name"],
                        "companySlug": c["slug"],
                        "sector": c["sector"],
                        "author": c.get("author", {}).get("name"),
                        "branch": b["name"],
                        "branchId": b["id"],
                        "branchRole": b["role"],
                        "location": b["location"],
                        "segment": fw["segment"],
                        "product": chosen["product"],
                        "vendor": chosen["vendor"],
                        "throughputGbps": chosen.get("throughputGbps"),
                        "priceUsd": chosen.get("priceUsd"),
                        "ruleCount": len(fw["rules"]),
                        "actions": {a: action_counts.get(a, 0) for a in ACTIONS},
                        "alternativesCount": len(fw["alternatives"]),
                        "alternatives": [
                            {
                                "product": a["product"],
                                "vendor": a["vendor"],
                                "throughputGbps": a.get("throughputGbps"),
                                "priceUsd": a.get("priceUsd"),
                            }
                            for a in fw["alternatives"]
                        ],
                    }
                )

    prices = [r["priceUsd"] for r in rows if r["priceUsd"] is not None]
    vendors = Counter(r["vendor"] for r in rows)
    products = Counter(f'{r["vendor"]} {r["product"]}' for r in rows)
    considered = Counter()
    for r in rows:
        considered[r["vendor"]] += 1
        for a in r["alternatives"]:
            considered[a["vendor"]] += 1

    return {
        "generatedBy": "firewall-lab/scripts/catalog.py",
        "contributors": contributors,
        "summary": {
            "companies": len({r["companySlug"] for r in rows}),
            "branches": len({(r["companySlug"], r["branchId"]) for r in rows}),
            "firewalls": len(rows),
            "rules": sum(r["ruleCount"] for r in rows),
            "priceUsd": {
                "min": min(prices) if prices else None,
                "max": max(prices) if prices else None,
                "total": sum(prices) if prices else 0,
            },
            "chosenByVendor": dict(vendors.most_common()),
            "chosenByProduct": dict(products.most_common()),
            "vendorsConsidered": dict(considered.most_common()),
        },
        "firewalls": rows,
    }


def to_md(cat: dict) -> str:
    s = cat["summary"]
    lines = [
        "# firewall-lab catalog",
        "",
        "Auto-generated by [`scripts/catalog.py`](scripts/catalog.py) from every "
        "`companies/<slug>/company.json`. Do not edit by hand — it is rebuilt on each PR.",
        "",
        "## Totals",
        "",
        f"- **{s['companies']}** companies · **{s['branches']}** branches · "
        f"**{s['firewalls']}** firewalls · **{s['rules']}** rules",
    ]
    if s["priceUsd"]["total"]:
        p = s["priceUsd"]
        lines.append(f"- Chosen-product spend: ${p['total']:,} (range ${p['min']:,}–${p['max']:,})")
    lines += ["", "## Chosen products by vendor", ""]
    for vendor, n in s["chosenByVendor"].items():
        lines.append(f"- {vendor}: {n}")
    lines += ["", "## Every firewall", "",
              "| Company | Branch | Segment | Chosen product | Vendor | Gbps | Price | Rules | a/d/r/l | Alts |",
              "|---|---|---|---|---|--:|--:|--:|:-:|--:|"]
    for r in cat["firewalls"]:
        a = r["actions"]
        gbps = r["throughputGbps"] if r["throughputGbps"] is not None else "—"
        price = f"${r['priceUsd']:,}" if r["priceUsd"] is not None else "—"
        lines.append(
            f"| {r['company']} | {r['branch']} | {r['segment']} | {r['product']} | {r['vendor']} "
            f"| {gbps} | {price} | {r['ruleCount']} "
            f"| {a['allow']}/{a['deny']}/{a['reject']}/{a['limit']} | {r['alternativesCount']} |"
        )
    lines += ["", "_a/d/r/l = allow / deny / reject / limit rule counts._", ""]
    return "\n".join(lines)


def write(cat: dict) -> None:
    JSON_OUT.write_text(json.dumps(cat, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    MD_OUT.write_text(to_md(cat) + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit non-zero if the committed catalog is stale")
    args = ap.parse_args(argv)

    cat = collect()
    if args.check:
        want_json = json.dumps(cat, ensure_ascii=False, indent=2) + "\n"
        want_md = to_md(cat) + "\n"
        stale = []
        if not JSON_OUT.exists() or JSON_OUT.read_text(encoding="utf-8") != want_json:
            stale.append("catalog.json")
        if not MD_OUT.exists() or MD_OUT.read_text(encoding="utf-8") != want_md:
            stale.append("catalog.md")
        if stale:
            print("stale (run: python3 firewall-lab/scripts/catalog.py): " + ", ".join(stale))
            return 1
        print("catalog up to date.")
        return 0

    write(cat)
    print(f"Wrote {JSON_OUT.relative_to(ROOT.parent)} and {MD_OUT.relative_to(ROOT.parent)} "
          f"({cat['summary']['firewalls']} firewalls).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
